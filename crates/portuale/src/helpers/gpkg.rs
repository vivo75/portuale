/// `gpkg.checksums` and `_record_checksum`.
#[derive(Default)]
struct Checksums {
    records: Vec<Vec<String>>,
}

impl Checksums {
    fn manifest(&self) -> Vec<u8> {
        let mut out = Vec::new();
        for r in &self.records {
            out.extend(r.join(" ").into_bytes());
            out.push(b'\n');
        }
        out
    }
}

