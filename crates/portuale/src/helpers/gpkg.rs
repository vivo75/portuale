fn now() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|d| d.as_secs() as i64)
        .unwrap_or(0)
}

#[derive(Clone, Copy)]
enum NameKind {
    User,
    Group,
}

/// A tar stream under construction: counts what it wrote so the end
/// padding can be computed (`TarFile.offset`).
struct Counted<'w> {
    w: &'w mut dyn Write,
    offset: u64,
}

